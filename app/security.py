""" 
Security layer
Input sanitization, PII detection/masking, output validation.
"""
import re
from langsmith import traceable

class InputSanittizer:
    INJECTION_PATTERNS = [
    r"ignore\s+(all\s+)?previous\s+instructions",
    r"forget\s+(all\s+)?previous",
    r"new\s+instructions\s*:",
    r"system\s*prompt",
    r"---\s*end\s*(of)?\s*prompt",
    r"pretend\s+you\s+are",
    r"act\s+as\s+(if\s+)?you",
    r"bypass\s+(all\s+)?restrictions",
    r"reveal\s+(your|the)\s+(system|instructions|prompt)",
    r"you\s+are\s+now\s+(DAN|jailbroken)",
]
    def __init__(self):
        self.patterns = [re.compile(p,re.IGNORECASE)
                         for p in self.INJECTION_PATTERNS]
    def check(self,text : str) -> tuple[bool, str | None]:
        """
        Check if input is safe
        Return:(is_safe, rejection_reason)
        """
        for pattern in self.patterns:
            if pattern.search(text):
                return False, "Blocked: patential prompt injection detected"
        return True, None
    def clean(self,text : str) -> str:
        """Remove potentially dangerous delimiters from input."""
        text = re.sub(r'[-]{3,}','',text)
        text = re.sub(r'[=]{3,}','',text)
        text = text.replace('{{','{ {').replace('}}','} }')
        return text.strip()
class PIIDetection():
    PATTERNS = {
    "email": re.compile(
        r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Z|a-z]{2,}\b'
    ),
    "phone": re.compile(r'\b\d{3}[-.]?\d{3}[-.]?\d{4}\b'),
    "ssn": re.compile(r'\b\d{3}-\d{2}-\d{4}\b'),
    "credit_card": re.compile(
        r'\b\d{4}[-\s]?\d{4}[-\s]?\d{4}[-\s]?\d{4}\b'
    ),
}
    MASK_MAP = {'email': '[EMAIL REDACTED]',
                'phone': '[PHONE REDACTED]',
                'ssn':  '[SSN REDACTED]',
                'credit_card': '[CARD REDACTED]'}
    def detect(self,text: str) -> dict[str,list[str]]:
        """Detect PII types present in text."""
        found = {}
        for pii_type, pattern in self.PATTERNS.items():
            matched = pattern.findall(text)
            if matched:
                found[pii_type] = matched 
        return found
    def mask(self,text : str) -> str:
        masked = text
        for pii_type, pattern in self.PATTERNS.items():
            masked = pattern.sub(self.MASK_MAP[pii_type],masked)       
        return masked
class OutputValidation:
    HARMFUL_PATTERNS = [
    re.compile(r"here('s| is) (how|the way) to (hack|steal|attack)", re.I),
    re.compile(r"password\s+is\s+", re.I),
    re.compile(r"api[_\s]?key\s*[:=]", re.I),
]
    def __init__(self):
        self.pii_detector = PIIDetection()
    def validate(self, output : str) -> tuple[str, list[str]]:
        """ 
        Validate and clean output
        Returns: (cleaned_ouput, list_of_warnings)
        """
        warnings = []
        pii_found = self.pii_detector.detect(output)
        if pii_found:
            output = self.pii_detector.mask(output)
            warnings.append(f"PII masked in ouput: {list(pii_found.keys())}")
        
        for pattern in self.HARMFUL_PATTERNS:
            if pattern.search(output):
                output = "[response blocked: potentially harmfull content]"
                warnings.append("Hamful content blocked")
                break
        return output, warnings
class SecurityPipeline:
    def __init__(self):
        self.sanitizer = InputSanittizer()
        self.pii_detector = PIIDetection()
        self.output_validation = OutputValidation()
    @traceable(name="security_check_input")
    def check_input(self, text : str) -> tuple[bool, str, list[str]]:
        """Process input through security checks

        Args:
            text (str): Input of user

        Returns:
            tuple[bool, str, list[str]]: [is allowed, cleaned text, security notes]
        """
        notes: list[str] = []
        # step 1: check for injection
        is_safe, reason = self.sanitizer.check(text)
        if not is_safe:
            notes.append(reason)
            return False, "" , notes
        
        # step 2: clean text
        cleaned_text = self.sanitizer.clean(text)
        
        # step 3: check PII
        pii_found = self.pii_detector.detect(text)
        if pii_found:
            cleaned_text = self.pii_detector.mask(text)
            notes.append(f"Input PII masked: {list(pii_found.keys())}")
        return True,cleaned_text,notes
    @traceable(name="security_check_output")
    def check_output(self,text) -> tuple[str,list[str]]:
        """Process the output was generated by AI

        Args:
            text (_type_): Ouput of AI

        Returns:
            tuple[str,list[str]]: [process ouput, list of warning detected]
        """
        return self.output_validation.validate(text) 
            